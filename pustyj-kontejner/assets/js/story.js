    if(!used.body)   arr.push({text:'Тело: осмотреть ещё раз',tag:'наблюдательность',goto:'s2_body'});
    if(!used.floor)  arr.push({text:'Пол: просветить бетон лампой',tag:'наблюдательность',goto:'s2_floor'});
