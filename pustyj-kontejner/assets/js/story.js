function trust(S, who, d){ S.trust[who] = (S.trust[who]||0)+d; }
function trustVal(S, who){ return S.trust[who]||0; }
function hasEv(S, e){ return !!S.evidence[e]; }
function addEvidence(S, e){
  if(!S.evidence[e]){ S.evidence[e]=true; toastEvidence(e); logLine(S, 'Улика: '+EVIDENCE_INFO[e][1]); }
}
function removeEvidence(S, e){ delete S.evidence[e]; }
function spendHour(S){
  const before=S.hours;
  S.hours = Math.max(0, S.hours-1);
  if(before>0 && S.hours===0){ S.flags.time_up=true; logLine(S,'⏰ Время вышло. Кравцов забирает дело.'); }
  updateClock();
}
// «часы кончились» — жёсткий обрыв расследования
function timeUp(S){ return S.hours<=0; }

/* определение финала */
function resolveEnding(S){
  if(S.endOverride==='sold' || S.flags.sold_out) return 'end_sold';
  if(S.flags.arrested) return 'end_clean';
  if(S.flags.time_up || S.endOverride==='fast') return 'end_hanging';
  if(S.flags.failed_alone || S.flags.bluffed_out) return 'end_against';
  if(S.flags.lida_sacrificed) return 'end_compromise';
  if(S.flags.false_confession || S.flags.fast_case || (hasEv(S,'E_КОШЕЛЁК') && !hasEv(S,'E_СЛЕДЫ'))) return 'end_hanging';
  // если дошли до рапорта без ареста и без сделки — считаем «один против всех» по духу
  return 'end_against';
}

/* проверка блефа про сейф: базовый исход — провал; с нужным статом или наблюдением — успех */
function bluffSuccess(S){
  return S.stats.cp>=3 || S.stats.ob>=3 || hasEv(S,'E_СЛЕДЫ') || hasEv(S,'E_ЛИДА');
}

